    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        try {
            Usuario usuario = SessaoUsuario.getUsuarioLogado();
            if (usuario == null) {
                JOptionPane.showMessageDialog(this, "Erro: nenhum usuário logado.");
                return;
            }

            usuario.setNome(txtNome.getText().trim());
            usuario.setEmail(txtEmail.getText().trim());
            usuario.setDataNascimento(txtNascimento.getText().trim());
            usuario.setTelefone(txtTelefone.getText().trim());
            usuario.setEndereco(txtEndereco.getText().trim());

            UsuarioController controller = new UsuarioController();
            controller.atualizar(usuario);

            JOptionPane.showMessageDialog(this, "Perfil atualizado com sucesso!");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar perfil: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

